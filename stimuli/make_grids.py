"""Generate the counting-task grids for the lottery-vs-fixed bonus study.

Every participant sees the same grids (in a random order chosen by the page),
so the answer key is fixed and lives in answer_key.csv.

Usage:
    python make_grids.py            # writes ../docs/grids.js, answer_key.csv, previews/
    python make_grids.py --no-png   # skip preview images

The seed is fixed so re-running produces byte-identical grids.
"""
import argparse
import csv
import json
import random
from pathlib import Path

SEED = 5306
ROWS = COLS = 10
TARGET = 7
N_SCORED = 10
# Target counts for the 10 scored grids: spread 8..20, all distinct so a
# worker can't guess a common answer.
TARGET_COUNTS = [8, 9, 11, 12, 13, 14, 15, 17, 18, 20]
# Distractor mix: half the non-targets are the look-alike digits 1 and 4,
# the rest are other digits. Keeps the task effortful but not impossible.
LOOKALIKES = [1, 4]
OTHERS = [0, 2, 3, 5, 6, 8, 9]
LOOKALIKE_SHARE = 0.5

ATTENTION_TARGETS = 3  # attention-check grid: all zeros plus three 7s


def make_grid(rng: random.Random, n_target: int) -> list[list[int]]:
    cells = ROWS * COLS
    n_look = round((cells - n_target) * LOOKALIKE_SHARE)
    n_other = cells - n_target - n_look
    flat = (
        [TARGET] * n_target
        + [rng.choice(LOOKALIKES) for _ in range(n_look)]
        + [rng.choice(OTHERS) for _ in range(n_other)]
    )
    rng.shuffle(flat)
    return [flat[r * COLS:(r + 1) * COLS] for r in range(ROWS)]


def make_attention_grid(rng: random.Random) -> list[list[int]]:
    flat = [0] * (ROWS * COLS)
    for i in rng.sample(range(ROWS * COLS), ATTENTION_TARGETS):
        flat[i] = TARGET
    return [flat[r * COLS:(r + 1) * COLS] for r in range(ROWS)]


def count_target(grid) -> int:
    return sum(v == TARGET for row in grid for v in row)


def render_png(grid, path: Path) -> None:
    from PIL import Image, ImageDraw, ImageFont

    cell = 40
    img = Image.new("RGB", (COLS * cell, ROWS * cell), "white")
    d = ImageDraw.Draw(img)
    try:
        font = ImageFont.truetype("DejaVuSans.ttf", 24)
    except OSError:
        font = ImageFont.load_default()
    for r, row in enumerate(grid):
        for c, v in enumerate(row):
            x, y = c * cell + cell / 2, r * cell + cell / 2
            d.text((x, y), str(v), fill="black", font=font, anchor="mm")
    img.save(path)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-png", action="store_true")
    args = ap.parse_args()

    here = Path(__file__).resolve().parent
    site = here.parent / "docs"
    rng = random.Random(SEED)

    grids = []
    for i, n in enumerate(TARGET_COUNTS):
        g = make_grid(rng, n)
        assert count_target(g) == n
        grids.append({"id": f"g{i + 1:02d}", "kind": "scored", "answer": n, "cells": g})
    att = make_attention_grid(rng)
    grids.append({"id": "attn", "kind": "attention", "answer": count_target(att), "cells": att})

    # The page loads grids from a plain JS file so it works from file:// too.
    (site / "grids.js").write_text(
        "// Generated by stimuli/make_grids.py - do not edit by hand.\n"
        f"window.GRIDS = {json.dumps(grids)};\n"
    )

    with open(here / "answer_key.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["grid_id", "kind", "answer"])
        for g in grids:
            w.writerow([g["id"], g["kind"], g["answer"]])

    if not args.no_png:
        out = here / "previews"
        out.mkdir(exist_ok=True)
        for g in grids:
            render_png(g["cells"], out / f"{g['id']}.png")

    print(f"Wrote {len(grids)} grids ({N_SCORED} scored + 1 attention check).")


if __name__ == "__main__":
    main()
